/**
 * Renders Oscar into the app icons (public/icons). Run: npx tsx scripts/make-icons.tsx
 * The art is the same Oscar component the app uses, rendered to static SVG.
 */
import { renderToStaticMarkup } from "react-dom/server";
import { chromium } from "playwright";
import { writeFileSync } from "node:fs";
import { Oscar } from "../components/oscar/Oscar";

function iconHtml(size: number, maskable: boolean) {
  const oscar = renderToStaticMarkup(<Oscar size={Math.round(size * (maskable ? 0.62 : 0.78))} pose="idle" alive={false} />);
  const radius = maskable ? 0 : Math.round(size * 0.22);
  return `<!doctype html><html><body style="margin:0;background:transparent">
  <div style="width:${size}px;height:${size}px;border-radius:${radius}px;overflow:hidden;display:flex;align-items:center;justify-content:center;
    background:radial-gradient(120% 120% at 30% 15%, #FFF7EC 0%, #F6E3D6 45%, #DCEBDD 100%);position:relative">
    <div style="position:absolute;left:0;right:0;bottom:0;height:${Math.round(size * 0.3)}px;background:#A9D18E;border-radius:50% 50% 0 0 / 30% 30% 0 0"></div>
    <div style="position:relative;transform:translateY(${Math.round(size * 0.04)}px)">${oscar}</div>
  </div></body></html>`;
}

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const jobs: [string, number, boolean][] = [
    ["icon-192.png", 192, false],
    ["icon-512.png", 512, false],
    ["maskable-512.png", 512, true],
    ["apple-touch-icon.png", 180, true],
    ["favicon-48.png", 48, false],
  ];
  for (const [name, size, maskable] of jobs) {
    await page.setViewportSize({ width: size, height: size });
    await page.setContent(iconHtml(size, maskable));
    await page.screenshot({ path: `public/icons/${name}`, omitBackground: !maskable, clip: { x: 0, y: 0, width: size, height: size } });
    console.log(name);
  }
  writeFileSync("public/icons/README.md", "Generated by `npx tsx scripts/make-icons.tsx` from the Oscar component. Original art.\n");
  await browser.close();
})();
